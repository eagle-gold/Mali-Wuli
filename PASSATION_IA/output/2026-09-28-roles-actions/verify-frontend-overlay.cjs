const fs=require('fs'),path=require('path');
const root='/Users/ibrahimakonate/Documents/ChatGPT/MALI-WULI-hostinger-integration/frontend';
const staging=path.join(__dirname,'staging/frontend');
const ts=require(path.join(root,'node_modules/typescript'));
const config=ts.readConfigFile(path.join(root,'tsconfig.json'),ts.sys.readFile);
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,root);
const mapped=(f)=>f.startsWith(root+'/')?path.join(staging,f.slice(root.length+1)):f;
const host=ts.createCompilerHost({...parsed.options,noEmit:true,incremental:false});
const origRead=host.readFile,origExists=host.fileExists;
host.readFile=f=>origRead(fs.existsSync(mapped(f))?mapped(f):f);
host.fileExists=f=>origExists(mapped(f))||origExists(f);
const origDir=host.directoryExists;
host.directoryExists=f=>origDir(mapped(f))||origDir(f);
const list=(dir)=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(d=>d.isDirectory()?list(path.join(dir,d.name)):[path.join(dir,d.name)]);
const added=list(staging).filter(f=>/\.tsx?$/.test(f)).map(f=>path.join(root,path.relative(staging,f)));
const program=ts.createProgram([...new Set([...parsed.fileNames,...added])],{...parsed.options,noEmit:true,incremental:false},host);
const diagnostics=ts.getPreEmitDiagnostics(program);
console.log(ts.formatDiagnosticsWithColorAndContext(diagnostics,{getCurrentDirectory:()=>root,getCanonicalFileName:f=>f,getNewLine:()=>"\n"}));
console.log(JSON.stringify({stagedFiles:added.length,diagnostics:diagnostics.length,emittedFiles:0}));
process.exitCode=diagnostics.length?1:0;
